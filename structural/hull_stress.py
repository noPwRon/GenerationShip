def ring_angular_velocity_rad_s(
    target_gravity_g: Optional[float] = None,
    radius_m: float = 100.0,
    g_std: float = 9.80665,
) -> float:
    """
    Angular velocity required to produce target centrifugal acceleration at ring wall.

    Formula:
        ω = √(g_target / r)

    Arguments:
        target_gravity_g : fraction of standard gravity (dimensionless).
            Pass 1.0 for 1 g, 0.5 for half-g, 1.2 for 20% above standard, etc.
            If None, defaults to 1.0 (full standard gravity).
            Internally multiplied by g_std to convert to m/s² before use.
            Do NOT pass raw m/s² here — use target_gravity_g=value/g_std if needed.
        radius_m : ring radius in metres (to the ring wall, not centreline).
        g_std : standard gravity in m/s². Override only if using non-SI conventions.

    TODO:
      [ ] Convert result to rpm and compare against RingGeometry.target_rpm_max
      [ ] Cite NASA-STD-3001 Vol 1 for acceptable rpm range
    """
    effective_g = g_std if target_gravity_g is None else target_gravity_g * g_std
    return np.sqrt(effective_g / radius_m)


